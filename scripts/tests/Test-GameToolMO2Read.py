    def test_source_change_between_passes_is_refused_without_retry(self):
        self.register()
        original = mo2._read_stable
        calls = {"modlist": 0}

        def changing(path, *, required):
            value = original(path, required=required)
            if Path(path).name == "modlist.txt":
                calls["modlist"] += 1
                if calls["modlist"] == 1:
                    (self.profile / "modlist.txt").write_text("+Changed\n", encoding="utf-8")
            return value

        with mock.patch.object(mo2, "_read_stable", side_effect=changing):
            with self.assertRaises(ModError) as raised:
                self.planning.inspect_instance("skyrim-main")
        self.assertEqual(raised.exception.code, "SOURCE_CHANGED")
        self.assertEqual(calls["modlist"], 2)

    def test_duplicate_unclassified_and_truncated_rows_remain_partial(self):
        (self.profile / "modlist.txt").write_text("+Same\n-same\nNoMarker\n", encoding="utf-8")
        self.before_protected = self._protected_tree()
        self.register()
        mods = self.planning.inspect_instance("skyrim-main")["inventory"]["mods"]
        self.assertFalse(mods["complete"])
        self.assertEqual(mods["duplicate_name_count"], 1)
        self.assertEqual(mods["rows"][-1]["declared_state"], "UNCLASSIFIED")
        self.assert_protected_unchanged()

        raw = "\n".join("+Mod %04d" % index for index in range(1001)).encode()
        parsed = mo2.parse_modlist(raw)
        self.assertEqual(len(parsed["rows"]), 1000)
        self.assertEqual(parsed["total_rows"], 1001)
        self.assertTrue(parsed["truncated"])
        self.assertFalse(parsed["complete"])

    def test_private_names_are_redacted_without_private_derived_tokens(self):
        private_path = "C:" + "\\" + "Users" + "\\private\\Secret Mod"
        secret = "ghp_" + "a" * 24
        file_uri = "file:" + "///" + "games/private/mod"
        (self.profile / "modlist.txt").write_text(
            "+" + private_path + "\n+" + secret + "\n+" + file_uri + "\n+Normal Mod\n",
            encoding="utf-8",
        )
        self.before_protected = self._protected_tree()
        self.register()
        inventory = self.planning.inspect_instance("skyrim-main")["inventory"]
        rows = inventory["mods"]["rows"]
        self.assertEqual(inventory["mods"]["redacted_name_count"], 3)
        self.assertFalse(inventory["mods"]["complete"])
        self.assertFalse(inventory["complete"])
        self.assertEqual([row["name"] for row in rows[:3]], ["[redacted-local-entry]"] * 3)
        self.assertEqual([row["mod_token"] for row in rows[:3]], [
            "mo2mod:redacted-0000", "mo2mod:redacted-0001", "mo2mod:redacted-0002",
        ])
        raw = json.dumps(rows)
        self.assertNotIn(private_path, raw)
        self.assertNotIn(secret, raw)
        self.assertNotIn(file_uri, raw)
        self.assertNotIn(hashlib.sha256(secret.casefold().encode()).hexdigest()[:24], raw)
        self.assertEqual(rows[-1]["name"], "Normal Mod")
        source = next(row for row in inventory["source_files"] if row["role"] == "modlist")
        self.assertIsNone(source["sha256"])
        self.assertFalse(source["raw_hash_exposed"])
        first_revision = inventory["state_revision"]
        replacement = "ghp_" + "c" * 24
        (self.profile / "modlist.txt").write_text(
            "+" + private_path + "\n+" + replacement + "\n+" + file_uri + "\n+Normal Mod\n",
            encoding="utf-8",
        )
        self.before_protected = self._protected_tree()
        second = self.planning.inspect_instance("skyrim-main")["inventory"]
        self.assertNotEqual(second["state_revision"], first_revision)
        self.assertNotIn(replacement, json.dumps(second))
        self.assertIsNone(next(row for row in second["source_files"] if row["role"] == "modlist")["sha256"])
        self.assert_protected_unchanged()

