class MO2ReadAdapterContracts(unittest.TestCase):
    def setUp(self):
        temp_parent = "/private/tmp" if sys.platform == "darwin" else None
        self.tmp = tempfile.TemporaryDirectory(dir=temp_parent)
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.data = self.root / "private"
        self.game = self.root / "Skyrim"
        self.manager = self.root / "MO2"
        self.profile = self.manager / "profiles" / "basic"
        self.game.mkdir()
        self.profile.mkdir(parents=True)
        (self.game / "SkyrimSE.exe").write_bytes(b"synthetic game marker\n")
        (self.manager / "ModOrganizer.exe").write_bytes(b"synthetic manager marker\n")
        (self.profile / "modlist.txt").write_text(
            "# This file was automatically generated by Mod Organizer.\n"
            "+SkyUI\n-Unofficial Patch\n*DLC: Dawnguard\n",
            encoding="utf-8-sig",
        )
        (self.profile / "plugins.txt").write_text(
            "# plugins\n*SkyUI_SE.esp\nDisabled.esp\n", encoding="utf-8",
        )
        self.service = WorkspaceAI(self.data)
        self.planning = PlanningService(self.service.workspaces)
        self.package = build_ai_test_package(ROOT, self.root / "package")
        self.foundation = FoundationService(self.service, source_root=self.package)
        self.before_protected = self._protected_tree()

    @staticmethod
    def _tree(root: Path):
        rows = []
        if root.exists():
            for path in sorted(root.rglob("*"), key=lambda value: value.as_posix().casefold()):
                if path.is_file():
                    rows.append((
                        path.relative_to(root).as_posix(),
                        path.stat().st_size,
                        hashlib.sha256(path.read_bytes()).hexdigest(),
                    ))
        return rows

    def _protected_tree(self):
        return {
            "game": self._tree(self.game),
            "manager": self._tree(self.manager),
        }

    def assert_protected_unchanged(self):
        self.assertEqual(self.before_protected, self._protected_tree())

    def register(self, instance_id="skyrim-main", profile=None, profile_label="basic"):
        return self.service.workspaces.instances.register_mo2_local(
            instance_id=instance_id,
            game_id="skyrim-special-edition",
            game_dir=self.game,
            manager_root=self.manager,
            profile_root=profile or self.profile,
            profile=profile_label,
            store="steam",
            build="synthetic",
            confirmed=True,
        )

    def test_registration_is_local_only_and_ordinary_route_refuses_missing_manager_binding(self):
        with self.assertRaises(ModError) as raised:
            self.service.workspaces.instances.register_mo2_local(
                instance_id="skyrim-main", game_id="skyrim-special-edition",
                game_dir=self.game, manager_root=self.manager, profile_root=self.profile,
                profile="basic", confirmed=False,
            )
        self.assertEqual(raised.exception.code, "LOCAL_APPROVAL_REQUIRED")
        with self.assertRaises(ModError) as raised:
            self.service.workspaces.instances.register_local(
                instance_id="skyrim-main", game_id="skyrim-special-edition",
                game_dir=self.game, confirmed=True,
            )
        self.assertEqual(raised.exception.code, "MANAGER_BINDING_REQUIRED")
        self.assertFalse(list((self.data / "game-instances").glob("*.json")))
        self.assert_protected_unchanged()

    def test_registration_writes_only_private_v2_metadata_and_public_results_are_path_free(self):
        result = self.register()
        self.assertTrue(result["metadata_written"])
        self.assertFalse(result["manager_files_written"])
        self.assertFalse(result["game_files_written"])
        self.assertEqual(result["instance"]["adapter"], "mo2")
        self.assertEqual(result["instance"]["record_schema_version"], 2)
        self.assertTrue(result["instance"]["manager_profile_registered"])
        record_path = self.data / "game-instances" / "skyrim-main.json"
        record = json.loads(record_path.read_text(encoding="utf-8"))
        self.assertEqual(record["schema_version"], 2)
        self.assertEqual(record["body"]["manager_binding"]["kind"], "mo2-profile")
        public = json.dumps([result, self.planning.inspect_instance("skyrim-main")])
        self.assertNotIn(str(self.root), public)
        self.assert_protected_unchanged()

    def test_same_binding_is_idempotent_and_duplicate_profile_owner_is_refused(self):
        self.register()
        second = self.register()
        self.assertFalse(second["metadata_written"])
        with self.assertRaises(ModError) as raised:
            self.register("skyrim-duplicate-profile")
        self.assertEqual(raised.exception.code, "INSTANCE_PATH_OWNED")
        self.assertEqual(len(list((self.data / "game-instances").glob("*.json"))), 1)
        self.assert_protected_unchanged()

    def test_case_alias_is_idempotent_and_cannot_create_second_profile_owner(self):
        self.register()
        aliases = [Path(str(path).upper()) for path in (self.game, self.manager, self.profile)]
        originals = (self.game, self.manager, self.profile)
        if not all(alias.exists() and os.path.samefile(original, alias)
                   for original, alias in zip(originals, aliases)):
            self.skipTest("Filesystem is case-sensitive; exact-path ownership is covered separately.")
        result = self.service.workspaces.instances.register_mo2_local(
            instance_id="skyrim-main", game_id="skyrim-special-edition",
            game_dir=aliases[0], manager_root=aliases[1], profile_root=aliases[2],
            profile="basic", store="steam", build="synthetic", confirmed=True,
        )
        self.assertFalse(result["metadata_written"])
        with self.assertRaises(ModError) as raised:
            self.service.workspaces.instances.register_mo2_local(
                instance_id="skyrim-alias-owner", game_id="skyrim-special-edition",
                game_dir=aliases[0], manager_root=aliases[1], profile_root=aliases[2],
                profile="basic", store="steam", build="synthetic", confirmed=True,
            )
        self.assertEqual(raised.exception.code, "INSTANCE_PATH_OWNED")
        self.assertEqual(len(list((self.data / "game-instances").glob("*.json"))), 1)
        self.assert_protected_unchanged()

    def test_same_game_and_manager_can_register_two_distinct_profiles(self):
        self.register()
        alternate = self.manager / "profiles" / "alternate"
        alternate.mkdir()
        (alternate / "modlist.txt").write_text("+Alternate Mod\n", encoding="utf-8")
        self.before_protected = self._protected_tree()
        self.register("skyrim-alternate", alternate, "alternate")
        listing = self.planning.list_instances("skyrim-special-edition")
        self.assertEqual(listing["count"], 2)
        self.assertEqual({row["profile"] for row in listing["instances"]}, {"basic", "alternate"})
        self.assertFalse(listing["truncated"])
        self.assert_protected_unchanged()

